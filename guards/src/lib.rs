/// Text styles shared by every design, so lettering looks the same across guards. The serif is
/// only used large enough for its thin strokes to stay sharp; everything small is the bold sans.
struct TextStyle {
    font: &'static Font,
    scale: f32,
    spacing: f32, // extra px between letters on ring text
}
const BAND: TextStyle = TextStyle { font: &TITLE, scale: 0.25, spacing: 2.5 }; // ring and banner text
const BAND_LONG: TextStyle = TextStyle { font: &TITLE, scale: 0.2, spacing: 1.5 }; // ring text too long for BAND
const HEADLINE: TextStyle = TextStyle { font: &POKER, scale: 0.25, spacing: 0.0 }; // big centre word
const LABEL: TextStyle = TextStyle { font: &POKER, scale: 0.19, spacing: 0.0 }; // centre captions
const CARD_INDEX: TextStyle = TextStyle { font: &TITLE, scale: 0.17, spacing: 0.0 }; // corner rank on court cards
const CARD_RANK: TextStyle = TextStyle { font: &TITLE, scale: 0.3, spacing: 0.0 }; // big rank on number cards
const ALERT: TextStyle = TextStyle { font: &TITLE, scale: 0.42, spacing: 0.0 }; // short warning words across the centre
const BIG_NUMBER: TextStyle = TextStyle { font: &TITLE, scale: 0.6, spacing: 0.0 }; // lone number filling the centre

fn text(s: &mut Smooth, t: &TextStyle, str: &str, x: f32, y: f32, c: u16) {
    s.text(t.font, t.scale, str, x, y, c);
}
// extra: additional letter spacing for designs that space their ring text out.
fn ring_text(s: &mut Smooth, t: &TextStyle, str: &str, r: f32, bottom: bool, c: u16, extra: f32) {
    let deg = if bottom { 90.0 } else { -90.0 };
    s.arc_text(t.font, t.scale, str, r, deg, t.spacing + extra, c, bottom);
}

/// Maps shape-local offsets to the screen: centred on (x, y), scaled by k, rotated by deg.
struct Place {
    x0: f32,
    y0: f32,
    k: f32,
    co: f32,
    sn: f32,
}
impl Place {
    fn new(x: f32, y: f32, k: f32, deg: f32) -> Self {
        Place { x0: x, y0: y, k, co: fcos(rad(deg)), sn: fsin(rad(deg)) }
    }
    fn x(&self, dx: f32, dy: f32) -> f32 {
        self.x0 + (dx * self.co - dy * self.sn) * self.k
    }
    fn y(&self, dx: f32, dy: f32) -> f32 {
        self.y0 + (dx * self.sn + dy * self.co) * self.k
    }
}

type Suit = fn(&mut Smooth, f32, f32, u16, f32, f32);

// Card suits about 18px tall times k, centred on (x, y), rotated by deg.
fn spade(s: &mut Smooth, x: f32, y: f32, c: u16, k: f32, deg: f32) {
    let p = Place::new(x, y, k, deg);
    s.tri(p.x(-7.6, 0.5), p.y(-7.6, 0.5), p.x(7.6, 0.5), p.y(7.6, 0.5), p.x(0.0, -9.0), p.y(0.0, -9.0), c);
    s.circle(p.x(-4.0, 2.0), p.y(-4.0, 2.0), 4.2 * k, c);
    s.circle(p.x(4.0, 2.0), p.y(4.0, 2.0), 4.2 * k, c);
    s.tri(p.x(0.0, 2.0), p.y(0.0, 2.0), p.x(-3.0, 9.0), p.y(-3.0, 9.0), p.x(3.0, 9.0), p.y(3.0, 9.0), c);
}
fn heart(s: &mut Smooth, x: f32, y: f32, c: u16, k: f32, deg: f32) {
    let p = Place::new(x, y, k, deg);
    s.circle(p.x(-4.2, -3.5), p.y(-4.2, -3.5), 4.8 * k, c);
    s.circle(p.x(4.2, -3.5), p.y(4.2, -3.5), 4.8 * k, c);
    s.tri(p.x(-8.8, -2.0), p.y(-8.8, -2.0), p.x(8.8, -2.0), p.y(8.8, -2.0), p.x(0.0, 8.5), p.y(0.0, 8.5), c);
}
fn club(s: &mut Smooth, x: f32, y: f32, c: u16, k: f32, deg: f32) {
    let p = Place::new(x, y, k, deg);
    s.circle(p.x(0.0, -4.5), p.y(0.0, -4.5), 4.0 * k, c);
    s.circle(p.x(-4.6, 1.5), p.y(-4.6, 1.5), 4.0 * k, c);
    s.circle(p.x(4.6, 1.5), p.y(4.6, 1.5), 4.0 * k, c);
    s.circle(x, y, 2.5 * k, c); // fills the gap where the three lobes meet
    s.tri(x, y, p.x(-3.0, 9.0), p.y(-3.0, 9.0), p.x(3.0, 9.0), p.y(3.0, 9.0), c);
}
fn diamond(s: &mut Smooth, x: f32, y: f32, c: u16, k: f32, deg: f32) {
    let p = Place::new(x, y, k, deg);
    let q = [p.x(0.0, -9.0), p.y(0.0, -9.0), p.x(7.0, 0.0), p.y(7.0, 0.0), p.x(0.0, 9.0), p.y(0.0, 9.0), p.x(-7.0, 0.0), p.y(-7.0, 0.0)];
    s.poly(&q, c);
}

fn chip_leader(s: &mut Smooth) {
    s.fill(BLACK);
    s.circle_grad(120.0, 120.0, 119.5, GOLD_L, GOLD_D, 113.0); // holes: inner circles cover the middle
    s.circle_grad(120.0, 120.0, 113.0, INK, INK, 84.0);
    s.circle_grad(120.0, 120.0, 84.0, GOLD_L, GOLD_D, 81.0);
    s.circle(120.0, 120.0, 81.0, PAPER);

    s.clip(81.0); // stripe stays inside the white face
    s.rect(0.0, 138.0, 240.0, 26.0, INK);
    s.clip(0.0);

    let outline = [73.5, 105.5, 166.5, 105.5, 166.5, 139.0, 120.0, 183.5, 73.5, 139.0];
    let body = [78.5, 110.5, 161.5, 110.5, 161.5, 137.0, 120.0, 176.5, 78.5, 137.0];
    s.poly(&outline, INK);
    s.poly(&body, PAPER);
    s.tri(84.0, 121.0, 117.0, 121.0, 117.0, 166.0, RED); // split by a white T, as on the coin
    s.tri(123.0, 121.0, 156.0, 121.0, 123.0, 166.0, INK);

    s.rect(67.0, 83.0, 106.0, 32.0, GOLD_D);
    s.rect(69.5, 85.5, 101.0, 27.0, GOLD);
    text(s, &HEADLINE, "POKER", 120.0, 99.0, RED);

    spade(s, 84.0, 66.0, INK, 1.0, 0.0);
    heart(s, 108.0, 66.0, RED, 1.0, 0.0);
    club(s, 132.0, 66.0, INK, 1.0, 0.0);
    diamond(s, 156.0, 66.0, RED, 1.0, 0.0);

    ring_text(s, &BAND, "THE CHIP LEADER", 97.0, false, GOLD, 0.0);

    // Laurel branches around the bottom, gold spade at the base.
    for side in [1, -1] {
        let (a0, a1): (f32, f32) = if side == 1 { (28.0, 80.0) } else { (152.0, 100.0) };
        s.arc(120.0, 120.0, 99.0, 1.6, a0.min(a1), a0.max(a1), GREEN_D);
        for k in 0..6 {
            let a = a0 + (a1 - a0) * (k as f32 + 0.5) / 6.0;
            for off in [-1, 1] {
                let r = 99.0 + (off * 6) as f32;
                let t = rad(a);
                s.ellipse(120.0 + r * fcos(t), 120.0 + r * fsin(t), 7.5, 3.2, a - (90 * side) as f32 + (off * 35 * side) as f32, GREEN);
            }
        }
    }
    spade(s, 120.0, 217.0, GOLD, 1.0, 0.0);
}

const CREAM: u16 = rgb565(244, 238, 222);
const DUCK: u16 = rgb565(250, 204, 60);
const DUCK_D: u16 = rgb565(196, 132, 20);
const BEAK: u16 = rgb565(240, 124, 24);

/// A cartoon duck facing left, body centred on (x, y), about 44 x 36 px.
/// Drawn twice: a slightly grown dark pass for the outline, then the fill.
fn duck(s: &mut Smooth, x: f32, y: f32, k: f32) {
    for pass in 0..2 {
        let g = if pass == 1 { 0.0 } else { 1.3 };
        let c = if pass == 1 { DUCK } else { DUCK_D };
        s.tri(x + 12.0 * k - g, y + 2.0 * k + g, x + 23.0 * k + g, y - 7.0 * k - g, x + 19.0 * k + g, y + 9.0 * k + g, c); // tail
        s.ellipse(x + 2.0 * k, y + 6.0 * k, 18.0 * k + g, 10.5 * k + g, -8.0, c); // body
        s.ellipse(x - 7.0 * k, y - 3.0 * k, 6.0 * k + g, 8.0 * k + g, 15.0, c); // neck
        s.circle(x - 9.0 * k, y - 12.0 * k, 8.5 * k + g, c); // head
        s.ellipse(x - 19.5 * k, y - 9.5 * k, 6.5 * k + g, 2.8 * k + g, 12.0, if pass == 1 { BEAK } else { DUCK_D }); // beak
    }
    s.ellipse(x + 5.0 * k, y + 4.0 * k, 10.0 * k, 5.5 * k, -18.0, DUCK_D); // wing
    s.ellipse(x + 5.0 * k, y + 3.5 * k, 8.6 * k, 4.2 * k, -18.0, DUCK);
    s.circle(x - 10.0 * k, y - 14.0 * k, 2.8 * k, PAPER); // eye
    s.circle(x - 11.0 * k, y - 14.0 * k, 1.5 * k, INK);
}

/// Shared frame: gold rim, cream band with suits down each side, black banners carrying top and
/// bottom text, gold rope ring, black centre (radius 73) for the design's own art.
fn banner_frame(s: &mut Smooth, top_style: &TextStyle, top: &str, bottom_style: &TextStyle, bottom: &str) {
    s.fill(BLACK);
    s.circle_grad(120.0, 120.0, 119.5, GOLD_L, GOLD_D, 112.0);
    s.circle_grad(120.0, 120.0, 112.0, CREAM, CREAM, 84.0);

    // Black banners with gold edges across the top and bottom of the band.
    for b in 0..2 {
        let (a0, a1) = if b == 1 { (38.0, 142.0) } else { (-142.0, -38.0) };
        s.arc(120.0, 120.0, 98.0, 30.0, a0, a1, GOLD);
        s.arc(120.0, 120.0, 98.0, 25.0, a0 + 1.5, a1 - 1.5, INK);
    }
    ring_text(s, top_style, top, 98.0, false, GOLD, 0.0);
    ring_text(s, bottom_style, bottom, 98.0, true, GOLD, 0.0);

    // Suits down each side of the band: club, diamond, spade, heart from top to bottom.
    for (i, side) in [-24.0f32, -8.0, 8.0, 24.0].into_iter().enumerate() {
        for left in [false, true] {
            let a = rad(if left { 180.0 - side } else { side });
            let (x, y) = (120.0 + 98.0 * fcos(a), 120.0 + 98.0 * fsin(a));
            match i {
                0 => club(s, x, y, INK, 1.0, 0.0),
                1 => diamond(s, x, y, RED, 1.0, 0.0),
                2 => spade(s, x, y, INK, 1.0, 0.0),
                _ => heart(s, x, y, RED, 1.0, 0.0),
            }
        }
    }

    // Gold ring with a twisted-rope inner edge around the black centre.
    s.circle_grad(120.0, 120.0, 85.0, GOLD_L, GOLD_D, 80.0);
    s.circle_grad(120.0, 120.0, 80.0, GOLD_D, GOLD_D, 73.0); // hole: the black centre covers it
    for i in 0..48 {
        let a = i as f32 * 7.5;
        let t = rad(a);
        s.ellipse(120.0 + 77.0 * fcos(t), 120.0 + 77.0 * fsin(t), 4.2, 1.9, a + 90.0 + 50.0, GOLD_L);
    }
    s.circle(120.0, 120.0, 73.0, INK);
}

