const SKIN: u16 = rgb565(248, 214, 170);
const HAIR: u16 = rgb565(140, 84, 36);
const CARD_EDGE: u16 = rgb565(110, 110, 110);

/// A 55 x 77 court card centred on (cx, cy), rotated by deg: a top-left index plus a simple
/// king (crown, beard) or jack (feathered hat) figure in a frame of the suit's colour, which takes
/// the rest of the card.
fn court_card(s: &mut Smooth, cx: f32, cy: f32, deg: f32, rank: u8, suit: Suit, col: u16) {
    let c = Place::new(cx, cy, 1.1, deg); // card space: 50 x 70 before scaling
    let f = Place::new(c.x(5.0, 2.7), c.y(5.0, 2.7), c.k * 1.3, deg); // figure space, centred in the frame
    #[allow(clippy::too_many_arguments)]
    let quad = |s: &mut Smooth, x0: f32, y0: f32, x1: f32, y1: f32, x2: f32, y2: f32, x3: f32, y3: f32, col: u16| {
        s.poly(&[f.x(x0, y0), f.y(x0, y0), f.x(x1, y1), f.y(x1, y1), f.x(x2, y2), f.y(x2, y2), f.x(x3, y3), f.y(x3, y3)], col);
    };
    let tri = |s: &mut Smooth, x0: f32, y0: f32, x1: f32, y1: f32, x2: f32, y2: f32, col: u16| {
        s.tri(f.x(x0, y0), f.y(x0, y0), f.x(x1, y1), f.y(x1, y1), f.x(x2, y2), f.y(x2, y2), col);
    };
    let circle = |s: &mut Smooth, x: f32, y: f32, r: f32, col: u16| s.circle(f.x(x, y), f.y(x, y), r * f.k, col);

    s.rrect(cx, cy, 52.5 * c.k, 72.5 * c.k, 5.0, deg, CARD_EDGE);
    s.rrect(cx, cy, 50.0 * c.k, 70.0 * c.k, 4.0, deg, PAPER);
    // Figure frame: right of the index column, 3.5 from the other edges.
    s.rrect(c.x(5.0, 0.0), c.y(5.0, 0.0), 33.0 * c.k, 63.0 * c.k, 2.0, deg, col);
    s.rrect(c.x(5.0, 0.0), c.y(5.0, 0.0), 30.0 * c.k, 60.0 * c.k, 1.5, deg, PAPER);

    quad(s, -11.0, 21.0, 11.0, 21.0, 8.0, 4.0, -8.0, 4.0, col); // robe with a gold sash
    quad(s, -2.5, 21.0, 2.5, 21.0, 1.5, 4.0, -1.5, 4.0, GOLD);
    if rank == b'K' {
        circle(s, 0.0, -1.0, 5.5, HAIR); // beard
        circle(s, 0.0, -5.0, 5.5, SKIN);
        quad(s, -6.0, -9.0, 6.0, -9.0, 6.0, -12.5, -6.0, -12.5, GOLD); // crown
        tri(s, -6.0, -12.5, -2.0, -12.5, -5.5, -18.5, GOLD);
        tri(s, -2.0, -12.5, 2.0, -12.5, 0.0, -19.5, GOLD);
        tri(s, 2.0, -12.5, 6.0, -12.5, 5.5, -18.5, GOLD);
    } else {
        circle(s, -5.0, -6.0, 2.6, HAIR);
        circle(s, 5.0, -6.0, 2.6, HAIR);
        circle(s, 0.0, -5.0, 5.5, SKIN);
        s.ellipse(f.x(0.0, -11.0), f.y(0.0, -11.0), 8.0 * f.k, 3.4 * f.k, deg, RED); // hat with a feather
        tri(s, 3.0, -12.0, 10.0, -20.0, 7.0, -10.5, GOLD);
    }
    circle(s, -2.0, -5.5, 0.9, INK); // eyes
    circle(s, 2.0, -5.5, 0.9, INK);

    // Top-left index only: rank over a small suit.
    s.glyph(CARD_INDEX.font, CARD_INDEX.scale, rank, c.x(-19.0, -26.0), c.y(-19.0, -26.0), deg, col);
    suit(s, c.x(-19.0, -14.0), c.y(-19.0, -14.0), col, 0.55, deg);
}

