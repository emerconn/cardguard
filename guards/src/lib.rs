/// Grinning cartoon donkey filling the centre: ears, head, muzzle, body, two hooves at the bottom.
fn donkey(s: &mut Smooth) {
    for pass in 0..2 {
        // dark grown pass = outline, then fill
        let g = if pass == 1 { 0.0 } else { 1.6 };
        let c = if pass == 1 { BROWN } else { BROWN_D };
        s.poly(&[112.0 - g, 116.0, 128.0 + g, 116.0, 131.0 + g, 143.0, 109.0 - g, 143.0], c); // neck, starts behind the muzzle
        s.ellipse(120.0, 155.0, 23.0 + g, 16.0 + g, 0.0, c); // rounded chest
        s.ellipse(101.0, 170.0, 15.0 + g, 8.5 + g, 132.0, c); // legs curving out to the hooves
        s.ellipse(139.0, 170.0, 15.0 + g, 8.5 + g, 48.0, c);
        s.ellipse(101.0, 57.0, 8.0 + g, 20.0 + g, -18.0, c); // ears
        s.ellipse(139.0, 57.0, 8.0 + g, 20.0 + g, 18.0, c);
        s.ellipse(120.0, 95.0, 27.0 + g, 30.0 + g, 0.0, c); // head
    }
    s.ellipse(101.0, 59.0, 4.0, 13.0, -18.0, TAN); // inside of the ears
    s.ellipse(139.0, 59.0, 4.0, 13.0, 18.0, TAN);
    s.tri(109.0, 72.0, 117.0, 70.0, 106.0, 58.0, BROWN_D); // tuft of mane
    s.tri(115.0, 70.0, 125.0, 70.0, 120.0, 54.0, BROWN_D);
    s.tri(123.0, 70.0, 131.0, 72.0, 134.0, 58.0, BROWN_D);

    for side in [-1.0f32, 1.0] {
        let ex = 120.0 + 11.0 * side;
        s.ellipse(ex, 89.0, 9.2, 11.2, 0.0, BROWN_D); // eyes
        s.ellipse(ex, 89.0, 8.0, 10.0, 0.0, PAPER);
        s.circle(ex - 3.0 * side, 92.0, 3.6, INK);
    }

    s.ellipse(120.0, 119.0, 22.5, 17.5, 0.0, BROWN_D); // muzzle
    s.ellipse(120.0, 119.0, 21.0, 16.0, 0.0, TAN);
    // Grin: a dark-rimmed half ellipse of teeth under a lip line, upturned corners, and the muzzle
    // showing below it as the lower lip.
    s.ellipse(120.0, 123.0, 15.0, 7.0, 0.0, INK);
    s.ellipse(120.0, 123.6, 13.4, 5.6, 0.0, PAPER);
    s.rect(103.0, 114.0, 34.0, 9.0, TAN);
    s.rect(105.0, 122.0, 30.0, 1.6, BROWN_D);
    s.ellipse(104.5, 121.0, 3.4, 1.1, 53.0, BROWN_D);
    s.ellipse(135.5, 121.0, 3.4, 1.1, -53.0, BROWN_D);
    s.ellipse(111.0, 113.0, 3.6, 2.4, -20.0, BROWN_D); // nostrils
    s.ellipse(129.0, 113.0, 3.6, 2.4, 20.0, BROWN_D);

    for side in [-1.0f32, 1.0] {
        let hx = 120.0 + 30.0 * side;
        // Bell-shaped hooves outlined in gold, with a shaggy dark fringe over the top and a split
        // (arch) at the bottom; drawn over the rope ring like the original.
        for pass in 0..3 {
            // dark rim so the gold edge stands off the gold ring behind
            let g = (2 - pass) as f32 * 1.3;
            let c = [INK, GOLD, HOOF][pass as usize];
            s.ellipse(hx, 183.0, 15.0 + g, 11.0 + g, 0.0, c);
            s.rrect(hx, 190.0, 34.0 + 2.0 * g, 14.0 + 2.0 * g, 5.0 + g, 0.0, c);
        }
        for pass in 0..2 {
            let d = if pass == 1 { 0.0 } else { 1.3 }; // gold copy shifted down edges the fringe's hem
            let c = if pass == 1 { INK } else { GOLD };
            s.ellipse(hx, 179.5 + d, 14.0, 6.5, 0.0, c);
            for i in 0..6 {
                let x = hx - 12.5 + (5 * i) as f32;
                s.tri(x - 3.0, 181.0 + d, x + 3.0, 181.0 + d, x, (if i % 2 == 1 { 187.0 } else { 189.5 }) + d, c);
            }
        }
        s.rrect(hx, 193.6, 8.2, 8.0, 4.1, 0.0, GOLD); // split: a small arch open at the bottom
        s.rrect(hx, 194.6, 5.4, 7.4, 2.7, 0.0, INK);
    }
}

fn donk(s: &mut Smooth) {
    s.fill(BLACK);
    s.circle_grad(120.0, 120.0, 119.5, GOLD_L, GOLD_D, 112.0);
    s.circle_grad(120.0, 120.0, 112.0, INK, INK, 86.0);
    s.circle_grad(120.0, 120.0, 86.0, GOLD_D, GOLD_D, 81.0); // rope ring; hole: the gold face covers it
    for i in 0..52 {
        let a = i as f32 * (360.0 / 52.0);
        let t = rad(a);
        s.ellipse(120.0 + 83.5 * fcos(t), 120.0 + 83.5 * fsin(t), 3.6, 1.5, a + 90.0 + 50.0, GOLD_L);
    }
    s.circle_grad(120.0, 120.0, 81.0, GOLD_L, GOLD, 0.0);

    ring_text(s, &BAND, "I'M A DONK", 99.0, false, GOLD, 5.0); // spaced out like the original
    ring_text(s, &BAND_LONG, "SEVEN TWO OFFSUIT", 99.0, true, GOLD, 0.0);
    for side in [-30.0f32, -15.0, 0.0, 15.0] {
        for left in [false, true] {
            let a = rad(if left { 180.0 - side } else { side });
            star(s, 120.0 + 99.0 * fcos(a), 120.0 + 99.0 * fsin(a), 6.5, GOLD);
        }
    }

    pip_card(s, 86.0, 124.0, -15.0, b'7', -1.0, spade, INK);
    pip_card(s, 154.0, 124.0, 15.0, b'2', 1.0, diamond, RED);
    donkey(s);
}

/// A gold revolver about 26 x 50 px times k pointing up, centred on (x, y); m = 1 puts the grip and
/// trigger guard to the right and the barrel and hammer to the left, -1 mirrors it.
fn revolver(s: &mut Smooth, x: f32, y: f32, k: f32, m: f32) {
    let (px, py) = (|dx: f32| x + dx * m * k, |dy: f32| y + dy * k);
    s.rect(px(-3.0) - 2.0 * k, py(-26.0), 4.0 * k, 26.0 * k, GOLD); // barrel, flush with the frame edge opposite the grip
    s.rrect(x, py(2.0), 10.0 * k, 14.0 * k, 2.5 * k, 0.0, GOLD); // cylinder
    s.rect(x - 3.0 * k, py(-2.0), 6.0 * k, 1.2 * k, INK);
    s.rect(x - 3.0 * k, py(3.0), 6.0 * k, 1.2 * k, INK);
    s.tri(px(-5.0), py(3.0), px(-5.0), py(9.0), px(-10.0), py(13.0), GOLD); // hammer spur, pointing back
    s.circle(px(7.5), py(10.0), 4.5 * k, GOLD); // trigger guard, under the cylinder in front of the grip
    s.circle(px(7.5), py(10.0), 2.8 * k, INK);
    s.poly(&[px(-5.0), py(8.0), px(3.0), py(8.0), px(10.0), py(25.0), px(2.0), py(27.0)], GOLD); // grip
}

fn bullets(s: &mut Smooth) {
    s.fill(BLACK);
    s.circle_grad(120.0, 120.0, 119.5, GOLD_L, GOLD_D, 113.0);
    s.circle_grad(120.0, 120.0, 113.0, INK, INK, 84.0);
    // Gold spokes split the band into the top and bottom text and the two gun panels.
    for a in [-138.0f32, -42.0, 42.0, 138.0] {
        let t = rad(a);
        let (c, n) = (fcos(t), fsin(t));
        let (dx, dy) = (-n * 1.2, c * 1.2);
        s.poly(&[120.0 + 84.0 * c + dx, 120.0 + 84.0 * n + dy, 120.0 + 113.0 * c + dx, 120.0 + 113.0 * n + dy, 120.0 + 113.0 * c - dx, 120.0 + 113.0 * n - dy, 120.0 + 84.0 * c - dx, 120.0 + 84.0 * n - dy], GOLD);
    }
    s.circle_grad(120.0, 120.0, 84.0, GOLD_L, GOLD_D, 79.0); // hole: the black centre covers it
    s.circle(120.0, 120.0, 80.0, BLACK); // smooth inner edge
    ring_text(s, &BAND, "BULLETS", 98.0, false, GOLD, 0.0);
    ring_text(s, &BAND, "PAIR OF ACES", 98.0, true, GOLD, 0.0);
    // Revolvers pointing up, each with three bullets above it.
    for (x, m) in [(26.0f32, 1.0f32), (214.0, -1.0)] {
        revolver(s, x, 140.0, 1.1, m);
        for (dx, y) in [(5.0, 75.0), (-5.5, 88.0), (-2.5, 101.0)] {
            s.rrect(x + m * dx, y, 4.2, 9.0, 2.1, 0.0, GOLD); // upright and staggered like the original
        }
    }

    pip_card(s, 101.0, 118.0, -12.0, b'A', -1.0, diamond, RED);
    diamond(s, 101.0 + 4.0, 118.0 + 10.0, RED, 1.5, -12.0);
    pip_card(s, 142.0, 122.0, 10.0, b'A', -1.0, spade, INK);
    spade(s, 142.0 + 2.0, 122.0 + 10.0, INK, 1.9, 10.0);
}

/// Shown briefly when a client asks for a guard that doesn't exist; not a guard itself.
pub fn no_guard(s: &mut Smooth, n: u32) {
    s.fill(BLACK);
    s.circle_grad(120.0, 120.0, 119.5, RED, RED, 112.0);
    text(s, &ALERT, "NO GUARD", 120.0, 80.0, GOLD);
    let mut buf = [0u8; 10];
    let mut i = buf.len();
    let mut v = n;
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    text(s, &BIG_NUMBER, core::str::from_utf8(&buf[i..]).unwrap(), 120.0, 140.0, PAPER);
}
