#!/usr/bin/env python3
"""Convert a TTF into an Adafruit GFXfont header (1-bit glyphs) using ImageMagick.

Usage: python3 tools/ttf2gfx.py /usr/share/fonts/liberation/LiberationSans-Bold.ttf 20 TitleFont [CHARS] > src/fonts.h
Only space, digits and capitals are included, or exactly CHARS if given, to keep the font small.
"""
import subprocess, sys

ttf, size, name = sys.argv[1], int(sys.argv[2]), sys.argv[3]
keep = set(sys.argv[4]) if len(sys.argv) > 4 else None
FIRST, LAST = 0x20, max(0x5A if keep is None else 0x20, *(ord(c) for c in keep or ()))
PAD = size * 2  # pen position inside the scratch canvas


def magick(*args):
    return subprocess.run(["magick", *args], check=True, capture_output=True).stdout


def glyph(ch):
    common = ["-font", ttf, "-pointsize", str(size)]
    adv = int(magick(*common, "label:|" + ch + "|", "-format", "%w", "info:")) - int(magick(*common, "label:||", "-format", "%w", "info:"))
    if ch == " ":
        return adv, 0, 0, 0, 0, b""
    canvas = ["-size", f"{PAD * 3}x{PAD * 3}", "xc:black", *common, "-fill", "white", "-annotate", f"+{PAD}+{PAD}", ch, "-threshold", "50%"]
    w, h, x, y = map(int, magick(*canvas, "-trim", "-format", "%w %h %X %Y", "info:").split())
    bits = magick(*canvas, "-trim", "+repage", "-depth", "8", "gray:-")
    return adv, w, h, x - PAD, y - PAD, bytes(1 if b > 127 else 0 for b in bits)


bitmap, glyphs = [], []
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    if not (ch in keep if keep else ch == " " or ch.isupper() or ch.isdigit()):
        glyphs.append((len(bitmap), 0, 0, 0, 0, 0))
        continue
    adv, w, h, xo, yo, px = glyph(ch)
    assert len(px) == w * h
    off = len(bitmap)
    acc = 0
    for i, b in enumerate(px):
        acc = acc << 1 | b
        if i % 8 == 7:
            bitmap.append(acc)
            acc = 0
    if len(px) % 8:
        bitmap.append(acc << (8 - len(px) % 8))
    glyphs.append((off, w, h, adv, xo, yo))

print(f"// {ttf} at {size}px, generated by tools/ttf2gfx.py")
print(f"const uint8_t {name}Bitmaps[] PROGMEM = {{")
for i in range(0, len(bitmap), 24):
    print("  " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
print("};")
print(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
for g in glyphs:
    print("  {%d, %d, %d, %d, %d, %d}," % g)
print("};")
print(f"const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, 0x{FIRST:02X}, 0x{LAST:02X}, {size + size // 4}}};\n")
