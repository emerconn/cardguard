#!/bin/sh
# Regenerate guards/src/fonts.rs. Add any new characters a design uses to the lists below.
# Fonts are stored at 4x and drawn by guards/src/smooth.rs at scale 0.25 (or smaller) for smooth edges.
set -e
cd "$(dirname "$0")/.."
F=/usr/share/fonts/liberation
{
  echo '// Generated by tools/fonts.sh; do not edit.'
  echo 'use crate::smooth::{g, Font};'
  echo
  python3 tools/ttf2gfx.py $F/LiberationSans-Bold.ttf 72 TITLE " '-0123456789ABCDEFGHIJKLMNOPQRSTUVW"
  python3 tools/ttf2gfx.py $F/LiberationSerif-Bold.ttf 108 POKER " 2CEKOPRTs"
} > guards/src/fonts.rs
